const fs = require('fs');
const path = require('path');
const { PNG } = require('pngjs');

const spritesDir = path.join(__dirname, '..', 'assets', 'sprites');
const outFile = path.join(__dirname, '..', 'src', 'assets', 'AssetManifest.ts');

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.name.toLowerCase().endsWith('.png')) {
      const rel = path.relative(spritesDir, full).split(path.sep).join('/');
      out.push(rel);
    }
  }
  return out.sort();
}

const files = walk(spritesDir);
const lines = [];
lines.push('// GENERATED by tools/generate-manifest.js - DO NOT EDIT MANUALLY');
lines.push('// Mapeia todos os arquivos reais de assets/sprites/.');
lines.push('// Caminhos relativos a assets/sprites/.');
lines.push('');
lines.push('export const ASSET_FILES: Record<string, number> = {');
for (const f of files) {
  const rel = '../../assets/sprites/' + f;
  lines.push(`  ${JSON.stringify(f)}: require(${JSON.stringify(rel)}),`);
}
lines.push('};');
lines.push('');
lines.push(`export const ASSET_KEYS: string[] = Object.keys(ASSET_FILES);`);
lines.push(`export const ASSET_COUNT = ${files.length};`);

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`Manifest gerado: ${files.length} assets -> src/assets/AssetManifest.ts`);

const geometry = [];
for (const file of files.filter((f) => f.startsWith('Buildings/'))) {
  const image = PNG.sync.read(fs.readFileSync(path.join(spritesDir, file)));
  let minX = image.width, maxX = 0, bottom = 0;
  for (let y = 0; y < image.height; y++) {
    for (let x = 0; x < image.width; x++) {
      if (image.data[(y * image.width + x) * 4 + 3] <= 200) continue;
      minX = Math.min(minX, x); maxX = Math.max(maxX, x + 1); bottom = y + 1;
    }
  }
  let sumX = 0, count = 0;
  for (let x = minX; x < maxX; x++) {
    if (image.data[((bottom - 1) * image.width + x) * 4 + 3] <= 200) continue;
    sumX += x + 0.5; count++;
  }
  if (!count) throw new Error(`No opaque building base: ${file}`);
  const anchorX = Math.round(sumX / count * 100) / 100;
  const span = Math.max(anchorX - minX, maxX - anchorX);
  geometry.push(`  ${JSON.stringify(path.basename(file, '.png'))}: { anchorX: ${anchorX}, anchorY: ${bottom}, span: ${span} },`);
}
fs.writeFileSync(path.join(__dirname, '../src/assets/BuildingGeometry.ts'), [
  '// Generated by tools/generate-manifest.js; translucent shadows are excluded from ground anchors.',
  'export const BUILDING_GEOMETRY: Record<string, { anchorX: number; anchorY: number; span: number }> = {',
  ...geometry, '};', '',
].join('\n'));
console.log(`Building ground anchors generated: ${geometry.length}`);
